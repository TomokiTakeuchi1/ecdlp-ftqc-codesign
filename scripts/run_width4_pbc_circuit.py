"""Emit a reproducible width-4 adaptive PBC circuit from the pinned fixture."""

from __future__ import annotations

import json
import platform
import subprocess
import sys
from collections import Counter
from hashlib import sha256
from pathlib import Path
from typing import Any

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from ecdlp_ftqc.circuits import (  # type: ignore[import-untyped]
    PINNED_GIDNEY_SOURCE_COMMIT,
    load_gidney_oracle_dag,
)
from ecdlp_ftqc.compiler import (  # type: ignore[import-untyped]
    PbcOperationKind,
    lower_gidney_phase_exact,
    lower_to_adaptive_pauli_measurements,
    pbc_trace_to_data,
    verify_reference_gadget_channels,
)

TASK_ID = "T-20260824-002"
EXPERIMENT_ID = "E-20260824-002"
WIDTH = 4
RANDOM_SEED = 20260815
FIXTURE_ROOT = PROJECT_ROOT / "tests" / "fixtures" / "gidney_oracle"
FIXTURE_PATH = FIXTURE_ROOT / "gidney_width4_oracle_v3.json"
OUTPUT_DIR = PROJECT_ROOT / "experiments" / "runs" / TASK_ID


def _sha256(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def _write_json(path: Path, data: Any) -> None:
    path.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def _git(*arguments: str) -> str:
    completed = subprocess.run(
        ["git", "-C", str(PROJECT_ROOT), *arguments],
        check=False,
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip()


def _verify_fixture() -> str:
    manifest_path = FIXTURE_ROOT / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest["source_commit"] != PINNED_GIDNEY_SOURCE_COMMIT:
        raise AssertionError("fixture manifest is not bound to the pinned source commit")
    record = next(
        item for item in manifest["files"] if item["name"] == FIXTURE_PATH.name
    )
    fixture_hash = _sha256(FIXTURE_PATH)
    if fixture_hash != record["sha256"] or FIXTURE_PATH.stat().st_size != record["bytes"]:
        raise AssertionError("width-4 fixture bytes do not match the pinned manifest")
    return fixture_hash


def _measurement_family(operation: dict[str, Any]) -> str:
    return "".join(term.split(":", maxsplit=1)[0] for term in operation["pauli_terms"])


def _escape_markdown(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _operation_detail(operation: dict[str, Any]) -> str:
    if operation["kind"] == PbcOperationKind.PREPARE.value:
        choices = []
        for choice in operation["prepared_states"]:
            condition = choice["condition"]
            suffix = f" if {condition}" if condition else ""
            choices.append(f"prepare {choice['state']}{suffix}")
        return "; ".join(choices)
    if operation["kind"] == PbcOperationKind.MEASURE_PAULI.value:
        return "M(" + " ".join(operation["pauli_terms"]) + ")"
    if operation["frame_updates"]:
        updates = []
        for update in operation["frame_updates"]:
            trigger = " xor ".join(update["parity_tokens"]) or "1"
            if update["condition"]:
                trigger += f" and {update['condition']}"
            updates.append(
                f"{update['pauli']} on {update['carrier_id']} if {trigger}"
            )
        return "; ".join(updates)
    return str(operation["note"])


def _write_readable_circuit(path: Path, trace_data: dict[str, Any]) -> None:
    lines = [
        "# Generated width-4 Gidney adaptive PBC circuit",
        "",
        "Generated by `scripts/run_width4_pbc_circuit.py`; do not edit manually.",
        "",
        "This is the processor-resident, quantum-output-preserving adaptive PBC lowering. ",
        "Durations and strict backend runtime remain `CHECK`.",
        "",
        "| Index | Kind | Logical support | PBC action | Classical input | Classical output |",
        "|---:|---|---|---|---|---|",
    ]
    for index, operation in enumerate(trace_data["operations"]):
        lines.append(
            "| "
            + " | ".join(
                _escape_markdown(value)
                for value in (
                    index,
                    operation["kind"],
                    ", ".join(operation["logical_support"]),
                    _operation_detail(operation),
                    ", ".join(operation["classical_inputs"]),
                    ", ".join(operation["classical_outputs"]),
                )
            )
            + " |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    fixture_hash = _verify_fixture()
    dag = load_gidney_oracle_dag(FIXTURE_PATH)
    if dag.width != WIDTH:
        raise AssertionError(f"expected width {WIDTH}, observed {dag.width}")

    logical_trace = lower_gidney_phase_exact(dag)
    pbc_trace = lower_to_adaptive_pauli_measurements(logical_trace)
    trace_data = pbc_trace_to_data(pbc_trace)

    operation_counts = Counter(operation["kind"] for operation in trace_data["operations"])
    measurement_counts = Counter(
        _measurement_family(operation)
        for operation in trace_data["operations"]
        if operation["kind"] == PbcOperationKind.MEASURE_PAULI.value
    )
    expected = {
        "operation_count": 113 * WIDTH - 131,
        "measurement_count": 53 * WIDTH - 62,
        "compiler_ancilla_lifetime_count": 20 * WIDTH - 23,
        "resource_state_demand": 4 * WIDTH - 4,
    }
    observed = {
        "operation_count": len(trace_data["operations"]),
        "measurement_count": trace_data["measurement_count"],
        "compiler_ancilla_lifetime_count": len(trace_data["compiler_ancillas"]),
        "resource_state_demand": trace_data["resource_state_demand"],
    }
    if observed != expected:
        raise AssertionError(f"generated identities changed: {observed=} {expected=}")

    verification = verify_reference_gadget_channels(random_seed=RANDOM_SEED)
    if verification.maximum_frobenius_error >= 1e-12:
        raise AssertionError("reference PBC gadget channel verification failed")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    trace_path = OUTPUT_DIR / "gidney_width4_pbc_trace.json"
    readable_path = OUTPUT_DIR / "gidney_width4_pbc_circuit.md"
    _write_json(trace_path, trace_data)
    _write_readable_circuit(readable_path, trace_data)
    _write_json(
        OUTPUT_DIR / "summary.json",
        {
            "compiler_ancilla_lifetime_count": observed[
                "compiler_ancilla_lifetime_count"
            ],
            "evidence_status": "NUMERICAL",
            "experiment_id": EXPERIMENT_ID,
            "fixture_exhaustive_phase_verification": True,
            "gadget_channel_maximum_frobenius_error": (
                verification.maximum_frobenius_error
            ),
            "measurement_family_counts": dict(sorted(measurement_counts.items())),
            "minimum_serial_processor_occupancy": trace_data[
                "minimum_serial_processor_occupancy"
            ],
            "operation_count": observed["operation_count"],
            "operation_counts": dict(sorted(operation_counts.items())),
            "peak_source_processor_occupancy": trace_data[
                "peak_source_processor_occupancy"
            ],
            "resource_state_demand": observed["resource_state_demand"],
            "runtime_evidence_status": "CHECK",
            "strict_runtime_available": False,
            "task_id": TASK_ID,
            "width": WIDTH,
        },
    )
    _write_json(
        OUTPUT_DIR / "reproducibility.json",
        {
            "circuit_source_commit": PINNED_GIDNEY_SOURCE_COMMIT,
            "experiment_id": EXPERIMENT_ID,
            "fixture_path": str(FIXTURE_PATH.relative_to(PROJECT_ROOT)),
            "fixture_sha256": fixture_hash,
            "git_commit": _git("rev-parse", "HEAD"),
            "input_trace": "runtime-metadata-benchmark/oracle v3",
            "lowered_trace": "ecdlp-ftqc/adaptive-pauli-measurement-trace v1",
            "output_path": str(OUTPUT_DIR.relative_to(PROJECT_ROOT)),
            "python": platform.python_version(),
            "random_seed": RANDOM_SEED,
            "script_sha256": _sha256(Path(__file__)),
            "task_id": TASK_ID,
            "validation_status": (
                "pinned fixture hash, generated-identity assertions, exhaustive "
                "source width-4 coherent regression, and branchwise reference-gadget "
                "channel verification; runtime CHECK"
            ),
            "working_tree_state": "dirty; see coordination/session record",
        },
    )


if __name__ == "__main__":
    main()
